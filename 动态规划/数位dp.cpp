#include <bits/stdc++.h>
using namespace std;
constexpr int N = 15;
using ll = long long;
ll l, r, dp[N], mi[N];
ll ans1[N], ans2[N];
int a[N];

void solve(ll n, ll *ans) {
	ll tmp = n;
	int len = 0;
	while (n)  // 分解数字n的各位数字，存入a数组（低位到高位）
		a[++len] = n % 10, n /= 10;
	for (int i = len; i >= 1; --i) {  // 从最高位到最低位处理
		for (int j = 0; j < 10; j++)  // 当前不是最高位时，当前位可以取0-9，所有低位贡献位dp[i - 1]
			ans[j] += dp[i - 1] * a[i];
		for (int j = 1; j < a[i];
		        j++)  // 当前是最高位时，当前位可以取1到a[i]-1，当前位的贡献次数为10^(i-1) (不能取0，因为不能有前导0)
			ans[j] += mi[i - 1];
		tmp -= mi[i - 1] * a[i];  // 更新剩余低位数值
		ans[a[i]] += tmp + 1;     // 当前是最高位并且取a[i]时，当前位贡献次数为剩余低位+1
	}
}

int main() {
	scanf("%lld%lld", &l, &r);
	mi[0] = 1ll;
	for (int i = 1; i <= 13; ++i) {
		dp[i] = dp[i - 1] * 10 + mi[i - 1];
		mi[i] = 10ll * mi[i - 1];
		cout << i << " " << dp[i] << endl;
	}
	solve(r, ans1), solve(l - 1, ans2);
	for (int i = 0; i < 10; ++i)
		printf("%lld ", ans1[i] - ans2[i]);
	return 0;
}

